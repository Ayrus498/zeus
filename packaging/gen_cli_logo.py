#!/usr/bin/env python3
"""Regenerate backend/app/cli/logo.py from the app icon (needs Pillow, build-time only).

The icon is resampled to SIZE x SIZE pixels and stored as hex colours, so the terminal UI can draw it with
half-block characters (two pixels per character cell) without any image library at runtime.
"""
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src-tauri" / "icons" / "source.png"
OUT = ROOT / "backend" / "app" / "cli" / "logo.py"
SIZE = int(sys.argv[1]) if len(sys.argv) > 1 else 26

im = Image.open(SRC).convert("RGBA")
# Area-average downscale (BOX): no ringing around the bolt edges.
im = im.resize((SIZE, SIZE), Image.BOX)
rows = []
for y in range(SIZE):
    row = []
    for x in range(SIZE):
        r, g, b, a = im.getpixel((x, y))
        row.append("......" if a < 110 else f"{r:02x}{g:02x}{b:02x}")
    rows.append("".join(row))
body = ",\n    ".join(repr(r) for r in rows)
OUT.write_text(f'''"""The ZEUS app icon as terminal pixels. Generated by packaging/gen_cli_logo.py - do not edit by hand."""
SIZE = {SIZE}
# One string per pixel row; six hex digits per pixel, "......" = transparent.
ROWS = [
    {body},
]
''')
print(f"wrote {OUT} ({SIZE}x{SIZE})")
